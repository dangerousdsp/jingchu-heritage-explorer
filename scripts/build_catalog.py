"""Read supplied workbook without altering it; build traceable app records."""
from pathlib import Path
import json,hashlib,openpyxl
ROOT=Path(__file__).resolve().parents[1]
source=ROOT.parent/'湖北省非遗数据.xlsx'
rows=list(openpyxl.load_workbook(source,read_only=True,data_only=True).active.values)
research_path=ROOT/'dist/researched-topics.json'
research=json.loads(research_path.read_text(encoding='utf-8-sig')) if research_path.exists() else []
if isinstance(research,dict):research=list(research.values())
by_fid={str(r['fid']):r for r in research}
areas={
'十堰市':['丹江口','房县','竹山','竹溪','郧西','郧阳','十堰'],
'襄阳市':['保康','谷城','老河口','南漳','枣阳','襄阳'],
'宜昌市':['当阳','五峰','伍家岗','兴山','宜都','远安','长阳','枝江','秭归','夷陵','宜昌'],
'恩施土家族苗族自治州':['巴东','恩施','鹤峰','来凤','利川','咸丰','宣恩'],
'咸宁市':['赤壁','崇阳','通山','咸宁'],
'黄石市':['大冶','阳新','黄石'],
'黄冈市':['红安','黄冈','蕲春','黄梅','麻城','团风','武穴'],
'荆州市':['公安','监利','荆州','石首','松滋'],
'鄂州市':['鄂州'],'荆门市':['京山','荆门'],'随州市':['随州'],
'天门市':['天门'],'潜江市':['潜江'],'仙桃市':['仙桃'],
'神农架林区':['神农架'],'武汉市':['武汉','京剧院'],'孝感市':['汉川','孝感','云梦']}
category_tips={
'民间文学':['留意故事中的地点、人物与口头讲述方式。','比较不同版本怎样表达共同记忆。'],
'传统音乐':['留意旋律、节奏与声部的配合。','从演唱或演奏的生活场景理解声音。'],
'传统舞蹈':['观察步伐、队形与身体节奏。','了解舞蹈与节庆、社区生活的联系。'],
'传统戏剧':['观察唱腔、角色和舞台动作。','从一段剧目中寻找地方语言的特点。'],
'曲艺':['留意说与唱之间的转换。','比较语言节奏、伴奏与叙事的关系。'],
'传统体育、游艺与杂技':['了解动作、器具与传习方式。','通过公开展示认识项目，不自行模仿高难动作。'],
'传统美术':['观察材料、色彩、纹样与构图。','想一想作品如何与日常生活相连。'],
'传统技艺':['区分原料、成型、加工与装饰环节。','关注技艺如何通过人的操作传承。'],
'传统医药':['从文化史与技艺传承角度阅读。','了解相关知识的历史背景与保护记录。'],
'民俗':['留意时间、仪式、参与者与活动空间。','理解习俗在社区生活中的意义。']}
records=[]
for row_index,row in enumerate(rows[1:],2):
    r={k:(v.strip() if isinstance(v,str) else v) for k,v in zip(rows[0],row)}
    fid=str(r['FID']); enriched=by_fid.get(fid,{})
    title=enriched.get('title',r['Name_CN'])
    display_place=r['Place_CN']
    if fid=='1996':display_place=display_place.replace('汉江区','江汉区')
    if fid=='3250':display_place=display_place.replace('省都区','曾都区')
    city=next((name for name,tokens in areas.items() if any(t in r['Place_CN'] for t in tokens)),None)
    # Province-wide declarations remain province-wide; coordinates do not establish a venue.
    if city is None and r['Place_CN']=='湖北省' and r['X']==112.891283:city='潜江市'
    city=city or '湖北省'
    tips=enriched.get('observations') or category_tips.get(r['CategoryCN'],['了解项目的地方特色与传承方式。'])
    record={'id':'hb-'+fid,'fid':fid,'title':title,'originalTitle':r['Name_CN'],'category':r['CategoryCN'],'region':display_place.replace('湖北省','') or '湖北全省','city':city,'year':r['Time'],'declarationType':r['Type_CN'],'unit':r['Unit_CN'],'projectNumber':r['Proj_num'],'sourceRow':row_index,'locationReference':{'lon':r['X'],'lat':r['Y'],'precision':'regional-reference','coordinateSystem':'unspecified','source':'用户提供的湖北省非遗数据.xlsx'},'researched':bool(enriched),'description':enriched.get('description') or (enriched.get('detail','')[:58]+'…' if enriched else f"走近{r['Place_CN'].replace('湖北省','') or '湖北'}的{title}，认识{r['CategoryCN']}中的地方传承。"),'detail':enriched.get('detail') or f"{title}是本次资料表中收录的{r['CategoryCN']}项目，记录的申报地区或单位为{r['Place_CN']}，公布年份为{r['Time']}年，记录类型为{r['Type_CN']}。表中保护单位为{r['Unit_CN']}。这些信息提供了继续查找项目历史与传承活动的线索。可通过官方名录与地区文化机构进一步了解。",'observations':tips,'sources':enriched.get('sources') or [{'title':'国家级非遗名录检索（按名称查询）','url':'https://www.ihchina.cn/project.html'}],'sourceNote':enriched.get('sourceNote') or '基础信息据用户提供的数据表整理；本条尚未补齐独立的项目详解，官方链接为继续查找入口。'}
    records.append(record)
(ROOT/'dist/catalog-data.mjs').write_text('// Generated by scripts/build_catalog.py. Raw workbook remains unchanged.\nexport const catalogData='+json.dumps(records,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
report={'source':source.name,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'sheet':'Sheet1','records':len(records),'distinct_coordinate_pairs':len(set((r['X'],r['Y']) for r in [dict(zip(rows[0],row)) for row in rows[1:]])),'researched':sum(r['researched'] for r in records),'coordinateSystem':'not supplied; do not use these as precise visit entrances','corrections':[{'fid':r['fid'],'row':r['sourceRow'],'original':r['originalTitle'],'display':r['title']} for r in records if r['title']!=r['originalTitle']]}
(ROOT/'docs/CATALOG_IMPORT.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'records':len(records),'researched':report['researched'],'coordinate_pairs':report['distinct_coordinate_pairs']},ensure_ascii=False))
